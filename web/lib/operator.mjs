// The voice operator: one long-lived Claude session per host that watches the fleet and acts
// on it for the user (what is running, who waits on input, reply / interrupt / close). It is
// an ordinary tmux session named `operator`, started in its own workspace directory (config
// web.operator.dir, under fleet's state dir) whose CLAUDE.md is the operator's brief and whose
// .claude/settings.json lets it run `fleet` and the local web API without permission prompts —
// a prompt would stall a conversation held by voice. The UI (Operator screen) talks to it with
// the ordinary send / messages routes, plus /api/transcribe in and /api/speak out.
import { promises as fs } from 'node:fs';
import path from 'node:path';

import { targetOf } from './fleet-cli.mjs';

export const OPERATOR_NAME = 'operator';

/** The host the operator's API helper calls: the bind address, or loopback for a wildcard bind. */
export function apiBase({ bind, port }) {
  const host = !bind || bind === '0.0.0.0' || bind === '::' ? '127.0.0.1' : bind.includes(':') ? `[${bind}]` : bind;
  return `http://${host}:${port}/api`;
}

/** `./api METHOD PATH [JSON]`: the local web API (it proxies other hosts), for the operator. */
export function apiScript(base) {
  return `#!/bin/sh
# The fleet web API on this machine (it reaches every host). Generated by fleet-web; do not edit.
# usage: ./api METHOD /path [JSON-BODY]     e.g. ./api GET /fleet
method="$1"; route="$2"; body="$3"
if [ -z "$method" ] || [ -z "$route" ]; then echo "usage: ./api METHOD /path [JSON]" >&2; exit 2; fi
if [ -n "$body" ]; then
  exec curl -sS -X "$method" -H 'content-type: application/json' --data "$body" "${base}$route"
else
  exec curl -sS -X "$method" "${base}$route"
fi
`;
}

/** The operator's CLAUDE.md. */
export function operatorBrief({ self, hosts }) {
  return `# Fleet operator

<!-- Generated by fleet-web on every operator start; edit CLAUDE.local.md for your own additions. -->

You are the user's **fleet operator**: a dispatcher for the coding-agent sessions (Claude Code,
Codex, pi) running in tmux on their machines (${hosts.map((h) => `\`${h}\``).join(', ')}; this one is \`${self}\`).
The user talks to you by voice, mostly from a phone: their messages are speech-to-text (expect
misheard names; match them to real sessions), and **your final reply is read aloud**.

## How you answer

- Speak, don't write: short plain sentences, no markdown, no tables, no code blocks, no bullet
  lists, no URLs, no session ids or paths. Two to five sentences is the norm; offer detail rather
  than dumping it ("want the details on the fleet repo one?").
- Answer in the language the user speaks (usually Croatian, Latin script). Keep English technical
  words (commit, PR, branch) as they are.
- Refer to sessions by their title or what they work on, plus the host when it matters.
- Always look before you answer: state comes from the commands below, never from memory — the
  fleet changes between turns.
- You are a session yourself (tmux \`${OPERATOR_NAME}\`, cwd = this directory). Leave every \`${OPERATOR_NAME}\`
  session out of reports — yours and any other host's.

## Seeing the fleet

- \`fleet list --all-hosts --json\` — every session: \`host\`, \`session_id\`, \`display_title\`, \`cwd\`,
  \`status\` (busy | idle | shell | waiting | unknown;
  \`shell\` is idle with a background Bash still running — never auto-cleared, that would end the shell), \`waiting_for\` (what a waiting session needs),
  \`updated_at\` (ms), \`tmux_session\`, \`context\`. Pipe through \`jq\` to keep it small.
- \`./api GET '/hosts/<host>/sessions/<id>/messages?limit=12'\` — a session's recent conversation
  (no tool calls). A pending AskUserQuestion is a message with \`kind: "question"\` and \`id\`.
- \`./api GET /hosts/<host>/sessions/<id>/brief\` — what it is doing, produced, still has to do.
- \`fleet -H <host> peek <id-prefix> --lines 40\` — the raw terminal, when messages are not enough.
- \`fleet -H <host> tmux stale --json\` — idle shells nothing uses. \`fleet usage\` — subscription limits.
- \`fleet prs\` — GitHub PRs that need the user.

## Acting on it

- Reply to a session: \`./api POST /hosts/<host>/sessions/<id>/send '{"text":"..."}'\`
- Answer its question: \`./api POST /hosts/<host>/sessions/<id>/answer '{"toolUseId":"<id>","answers":[{"options":[0]}]}'\`
  (one entry per question; option indexes from 0, or \`"text"\` for a free answer).
- Keys: \`./api POST /hosts/<host>/sessions/<id>/keys '{"key":"Escape"}'\` (interrupt), Enter, Up, Down.
- Close a session: \`./api POST /hosts/<host>/sessions/<id>/kill '{}'\`.
  Close a stale tmux shell: \`fleet -H <host> tmux kill <name> -f\`.
- Start one: \`./api POST /hosts/<host>/spawn '{"dir":"<abs dir>","prompt":"..."}'\`.

Rules:
- Before you send, answer or interrupt, be sure of the target. If more than one session could be
  meant, ask which one — never guess. Say what you sent and to whom in one sentence.
- Closing or killing anything, and interrupting busy work, needs an explicit yes from the user in
  this conversation first: name exactly what you would close and ask.
- Relay what the user says to a session faithfully; do not add your own instructions unless asked.

## Typical questions

- "What's going on / what are we doing?" → list, group by what they work on, one line each,
  waiting ones first.
- "Who's waiting on me?" → every \`waiting\` session: what it asks, in a sentence; offer to answer.
- "What's next / what's left?" → briefs' todos and the latest messages of the relevant sessions.
- "Clean up" → stale tmux shells and idle sessions untouched for a long time; propose, then confirm.
`;
}

/** The operator's .claude/settings.json: no permission prompts for what CLAUDE.md tells it to run. */
export function operatorSettings() {
  return {
    permissions: {
      allow: ['Bash(fleet:*)', 'Bash(./api:*)', 'Bash(jq:*)', 'Bash(date:*)'],
    },
  };
}

async function writeIfChanged(file, content, mode) {
  const current = await fs.readFile(file, 'utf8').catch(() => null);
  if (current === content) return;
  await fs.writeFile(file, content, { mode });
  if (mode) await fs.chmod(file, mode);
}

/** Sent to the idle operator: a fresh conversation (a new session id, no history in the app). */
export const CLEAR_COMMAND = '/clear';

/**
 * @param {object} deps
 *   config   normalized config (self, hosts, bind, port, operator: { dir, model, clearIdleMinutes })
 *   fleet    lib/fleet.mjs instance (localHost)
 *   spawner  lib/spawn.mjs spawner
 *   cli      lib/fleet-cli.mjs instance (send: the auto-clear, under the session's typing lock;
 *            absent → none)
 */
export function createOperator({ config, fleet, spawner, cli = null, now = Date.now, log = () => {}, checkEveryMs = 5 * 60 * 1000 }) {
  const dir = config.operator.dir;
  // The workspace's resolved path (a symlinked state dir), known after the first prepare().
  let real = dir;

  async function prepare() {
    await fs.mkdir(path.join(dir, '.claude'), { recursive: true });
    await writeIfChanged(path.join(dir, 'CLAUDE.md'), operatorBrief({ self: config.self, hosts: config.hosts }));
    await writeIfChanged(path.join(dir, '.claude', 'settings.json'), `${JSON.stringify(operatorSettings(), null, 2)}\n`);
    await writeIfChanged(path.join(dir, 'api'), apiScript(apiBase(config)), 0o755);
    real = await fs.realpath(dir).catch(() => dir);
  }

  /** Is this `fleet list` row an operator (a Claude session in the workspace)? */
  const isOperator = (s) => Boolean(s?.cwd && (s.cwd === dir || s.cwd === real) && (s.harness ?? 'claude') === 'claude');

  /** A host's list with `operator: true` on its operator row (the UI keeps it out of session lists). */
  const stamp = (host) => (Array.isArray(host?.sessions) && host.sessions.some(isOperator) ? { ...host, sessions: host.sessions.map((s) => (isOperator(s) ? { ...s, operator: true } : s)) } : host);

  /** This host's operator session, or null. */
  async function find({ force = false } = {}) {
    const host = await fleet.localHost({ force });
    if (!host.ok) return null;
    return host.sessions.find(isOperator) ?? null;
  }

  async function status() {
    return { host: config.self, dir, session: await find() };
  }

  /** Find the operator, or start it: `{ host, dir, session, started, tmuxSession }`. */
  async function ensure() {
    await prepare();
    const existing = await find({ force: true });
    if (existing) return { host: config.self, dir, session: existing, started: false, tmuxSession: existing.tmux_session ?? null };
    const result = await spawner.spawn({ name: OPERATOR_NAME, dir, prompt: '', nameGiven: true, model: config.operator.model, harness: 'claude' });
    return { host: config.self, dir, session: null, started: true, tmuxSession: result.tmuxSession };
  }

  // Auto-clear: an operator idle for clearIdleMinutes gets /clear — the next conversation starts
  // empty (Claude Code starts a new session, so the app shows no history). A cleared session has
  // no context yet, which is what keeps it from being cleared again.
  async function tick() {
    const idleMs = config.operator.clearIdleMinutes * 60 * 1000;
    if (!cli || !idleMs) return null;
    const s = await find({ force: true });
    // Plain `idle` only: Claude Code's `shell` has a background shell running, left alone.
    if (!s || s.status !== 'idle' || !s.updated_at || !s.context?.used) return null;
    if (now() - s.updated_at < idleMs) return null;
    // Through the CLI, like every web path that types: it holds the session's typing lock.
    await cli.send({ target: targetOf(s), text: CLEAR_COMMAND });
    log(`[fleet-web] operator: cleared ${s.session_id.slice(0, 8)} (idle ${Math.round((now() - s.updated_at) / 60000)}m)`);
    return s.session_id;
  }

  let timer = null;
  function start() {
    if (timer || !cli || !config.operator.clearIdleMinutes) return;
    timer = setInterval(() => tick().catch((err) => log(`[fleet-web] operator auto-clear: ${err?.message ?? err}`)), checkEveryMs);
    timer.unref?.();
  }
  function stop() {
    clearInterval(timer);
    timer = null;
  }

  return { status, ensure, prepare, find, isOperator, stamp, tick, start, stop, dir };
}
